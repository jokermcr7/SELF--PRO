def all_commands() -> str:
    """Compact text for `.راهنما`."""
    out = ["**🤖 راهنمای سلف**", "همه‌ی دستورها با نقطه شروع میشن؛ مثلاً `.آیدی`", ""]
    for title, feats in CATS:
        out.append(f"**{title}**")
        out.append(" ".join(f"`.{f[0]}`" for f in feats))
        out.append("")
    out.append("📖 توضیح و طرز استفاده‌ی هر دستور: ربات مدیریت ← «📖 راهنما» یا `.پنل` ← «📖 راهنما»")
    return "\n".join(out)


def feature_count() -> int:
    return sum(len(f) for _, f in CATS)


# ---------------------------------------------------------------- views (HTML text + Bot API rows)
import html
import re

GREEN, RED = "success", "danger"


def md2html(t: str) -> str:
    t = html.escape(t, quote=False)
    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    t = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", t)
    t = re.sub(r"__(.+?)__", r"<i>\1</i>", t)
    return t


def _b(text, data, style=None):
    d = {"text": text, "callback_data": data}
    if style:
        d["style"] = style
    return d


def find(cmd):
    for i, (_, feats) in enumerate(CATS):
        for j, f in enumerate(feats):
            if f[0] == cmd:
                return i, j
    return 0, 0


def tabs(mk, cur):
    nums = [_b(f"⌜{i + 1}⌝" if i == cur else str(i + 1), mk(f"c{i}"), RED) for i in range(len(CATS))]
    return [nums[:5], nums[5:]]


def grid_view(mk, back, i):
    """One of the 7 pages: 2 columns of green command buttons + numbered tabs + back."""
    title, feats = CATS[i]
    text = (f"<blockquote>Self Commands | دستورات سلف</blockquote>\n"
            f"<b>{html.escape(title)}</b>  ({i + 1}/{len(CATS)})\n"
            "روی هر دستور بزن تا توضیح و طرز استفاده‌اش رو ببینی 👇")
    rows, line = [], []
    for j, f in enumerate(feats):
        line.append(_b(f[0].replace("_", " "), mk(f"f{i}:{j}"), GREEN))
        if len(line) == 2:
            rows.append(line)
            line = []
    if line:
        rows.append(line)
    rows += tabs(mk, i)
    rows.append([_b("بازگشت به منوی اصلی", back, RED)])
    return text, rows


def feat_view(mk, i, j, state=None):
    title, feats = CATS[i]
    cmd, desc, usage, run = feats[j]
    text = f"<b>.{html.escape(cmd)}</b>\n<blockquote>{md2html(desc)}</blockquote>\n"
    text += "".join(f"<blockquote>{md2html(u)}</blockquote>\n" for u in usage)
    rows = []
    if cmd in TOGGLE_OF:
        on = (state or {}).get(cmd, TOGGLE_OF[cmd][1])
        rows.append([_b("روشن ⟨✓⟩" if on else "خاموش ⟨✗⟩", mk(f"t{i}:{j}"), GREEN if on else RED)])
    if cmd == "ساعت":
        rows.append([_b("⏰ بخش ساعت (اسم / فامیل / بیو / فونت)", mk("k"), GREEN)])
    if run:
        rows.append([_b("▶️ همین الان اجرا کن", mk(f"r{run}"), GREEN)])
    rows.append([_b("بازگشت به دستورات", mk(f"c{i}"), RED)])
    return text[:1000], rows


def view(path, mk, back, state=None):
    """path: '' | 'c<i>' | 'f<i>:<j>'. Returns (html text, Bot API rows)."""
    try:
        if path.startswith("f"):
            i, _, j = path[1:].partition(":")
            return feat_view(mk, int(i), int(j), state)
        if path.startswith("c"):
            return grid_view(mk, back, int(path[1:]))
    except (ValueError, IndexError):
        pass
    return grid_view(mk, back, 0)
