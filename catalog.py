def all_commands() -> str:
    """Compact text for `.راهنما`."""
    out = ["**🤖 راهنمای سلف**", "همه‌ی دستورها با نقطه شروع میشن؛ مثلاً `.آیدی`", ""]
    for title, feats in CATS:
        out.append(f"**{title}**")
        out.append(" ".join(f"`.{f[0]}`" for f in feats))
        out.append("")
    out.append("📖 توضیح و طرز استفاده‌ی هر دستور: ربات مدیریت ← «📖 همه‌ی دستورها» یا `.پنل` ← «قابلیت‌ها»")
    return "\n".join(out)


def feature_count() -> int:
    return sum(len(f) for _, f in CATS)


# ---------------------------------------------------------------- views (HTML text + Bot API rows)
import html
import re

GREEN, RED, BLUE = "success", "danger", "primary"


def md2html(t: str) -> str:
    t = html.escape(t, quote=False)
    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    t = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", t)
    t = re.sub(r"__(.+?)__", r"<i>\1</i>", t)
    return t


def _b(text, data, style=None):
    d = {"text": text, "callback_data": data}
    if style:
        d["style"] = style
    return d


def find(cmd):
    for i, (_, feats) in enumerate(CATS):
        for j, f in enumerate(feats):
            if f[0] == cmd:
                return i, j
    return 0, 0


def _pairs(buttons):
    return [buttons[k:k + 2] for k in range(0, len(buttons), 2)]


def root_view(mk, back):
    """Folders page: every folder is a button; pressing it opens that folder's features."""
    text = (f"<blockquote>Self Commands | دستورات سلف</blockquote>\n"
            f"<b>📂 قابلیت‌ها</b>  —  {len(CATS)} پوشه، {feature_count()} قابلیت\n"
            "یک پوشه رو بزن تا قابلیت‌هاش باز بشه 👇")
    rows = _pairs([_b(f"{title}  ·  {len(feats)}", mk(f"c{i}"), GREEN) for i, (title, feats) in enumerate(CATS)])
    rows.append([_b("بازگشت", back, RED)])
    return text, rows


def grid_view(mk, back, i):
    """One folder: 2 columns of feature buttons (clear names)."""
    title, feats = CATS[i]
    text = (f"<blockquote>Self Commands | دستورات سلف</blockquote>\n"
            f"<b>{html.escape(title)}</b>  ({len(feats)} قابلیت)\n"
            "روی هر قابلیت بزن تا توضیح و طرز استفاده‌اش رو ببینی 👇")
    rows = _pairs([_b(f[1], mk(f"f{i}:{j}"), GREEN) for j, f in enumerate(feats)])
    rows.append([_b("📂 همه‌ی پوشه‌ها", mk(""), RED), _b("بازگشت", back, RED)])
    return text, rows


def feat_view(mk, i, j, state=None):
    title, feats = CATS[i]
    cmd, name, desc, usage, run = feats[j]
    text = (f"<b>{html.escape(name)}</b>\n<code>.{html.escape(cmd)}</code>\n"
            f"<blockquote>{md2html(desc)}</blockquote>\n")
    text += "".join(f"<blockquote>{md2html(u)}</blockquote>\n" for u in usage)
    rows = []
    if cmd in TOGGLE_OF:
        on = (state or {}).get(cmd, TOGGLE_OF[cmd][1])
        rows.append([_b("روشن ⟨✓⟩" if on else "خاموش ⟨✗⟩", mk(f"t{i}:{j}"), GREEN if on else RED)])
    if cmd == "ساعت":
        rows.append([_b("⏰ بخش ساعت (اسم / فامیل / بیو / فونت)", mk("k"), GREEN)])
    if cmd == "حالت":
        rows.append([_b("🎨 بخش حالت خودکار (سبک‌ها و فونت)", mk("s"), GREEN)])
    if run:
        rows.append([_b("▶️ همین الان اجرا کن", mk(f"r{run}"), GREEN)])
    rows.append([_b(f"↩️ {title}", mk(f"c{i}"), RED), _b("📂 پوشه‌ها", mk(""), RED)])
    return text[:1000], rows


def view(path, mk, back, state=None):
    """path: '' (folders) | 'c<i>' (one folder) | 'f<i>:<j>' (one feature). Returns (html text, Bot API rows)."""
    try:
        if path.startswith("f"):
            i, _, j = path[1:].partition(":")
            return feat_view(mk, int(i), int(j), state)
        if path.startswith("c"):
            return grid_view(mk, back, int(path[1:]))
    except (ValueError, IndexError):
        pass
    return root_view(mk, back)
