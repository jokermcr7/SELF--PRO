def all_commands() -> str:
    """Compact text for `.راهنما`."""
    out = ["**🤖 راهنمای سلف**", "همه‌ی دستورها با نقطه شروع میشن؛ مثلاً `.آیدی`", ""]
    for title, feats in CATS:
        out.append(f"**{title}**")
        out.append(" ".join(f"`.{f[0]}`" for f in feats))
        out.append("")
    out.append("📖 توضیح و طرز استفاده‌ی هر دستور: ربات مدیریت ← «📖 راهنما» یا `.پنل` ← «📖 راهنما»")
    return "\n".join(out)


def feature_count() -> int:
    return sum(len(f) for _, f in CATS)


# ---------------------------------------------------------------- views (text + rows of (label, data))
def root_view(mk, back):
    text = (f"📖 **راهنمای کامل** — {feature_count()} قابلیت در {len(CATS)} بخش\n\n"
            "یک بخش رو انتخاب کن، بعد روی هر قابلیت بزن تا طرز کار و مثالش رو ببینی 👇")
    rows, line = [], []
    for i, (title, feats) in enumerate(CATS):
        line.append((f"{title} ({len(feats)})", mk(f"c{i}")))
        if len(line) == 2:
            rows.append(line)
            line = []
    if line:
        rows.append(line)
    rows.append([("⬅️ برگشت", back)])
    return text, rows


def cat_view(mk, i, page=0):
    title, feats = CATS[i]
    pages = (len(feats) + PAGE - 1) // PAGE
    page = max(0, min(page, pages - 1))
    chunk = feats[page * PAGE:(page + 1) * PAGE]
    text = f"**{title}**" + (f" — صفحه {page + 1}/{pages}" if pages > 1 else "") + "\nروی هر دستور بزن تا توضیحش رو ببینی 👇"
    rows, line = [], []
    for k, f in enumerate(chunk):
        line.append((f".{f[0]}", mk(f"f{i}:{page * PAGE + k}")))
        if len(line) == 2:
            rows.append(line)
            line = []
    if line:
        rows.append(line)
    if pages > 1:
        nav = []
        if page > 0:
            nav.append(("◀️ قبلی", mk(f"c{i}:{page - 1}")))
        if page < pages - 1:
            nav.append(("بعدی ▶️", mk(f"c{i}:{page + 1}")))
        rows.append(nav)
    rows.append([("⬅️ بخش‌ها", mk(""))])
    return text, rows


def feat_view(mk, i, j):
    title, feats = CATS[i]
    cmd, desc, usage, run = feats[j]
    text = (f"🔹 **.{cmd}**   ({title})\n\n📝 {desc}\n\n⌨️ **طرز استفاده:**\n" + "\n".join(f"• {u}" for u in usage))
    rows = []
    if run:
        rows.append([("▶️ همین الان اجرا کن", mk(f"r{run}"))])
    rows.append([("⬅️ برگشت", mk(f"c{i}:{j // PAGE}"))])
    return text, rows


def view(path, mk, back):
    """path: '' | 'c<i>[:page]' | 'f<i>:<j>'. Returns (text, rows)."""
    try:
        if path.startswith("c"):
            i, _, pg = path[1:].partition(":")
            return cat_view(mk, int(i), int(pg or 0))
        if path.startswith("f"):
            i, _, j = path[1:].partition(":")
            return feat_view(mk, int(i), int(j))
    except (ValueError, IndexError):
        pass
    return root_view(mk, back)
